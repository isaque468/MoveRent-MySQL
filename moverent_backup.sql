CREATE DATABASE IF NOT EXISTS `mydb` DEFAULT CHARACTER SET utf8mb3;
USE `mydb`;
SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS `trajeto`;
DROP TABLE IF EXISTS `locacao`;
DROP TABLE IF EXISTS `pessoas`;
DROP TABLE IF EXISTS `ciclomotor`;
CREATE TABLE `pessoas` (
 `CPF` varchar(11) NOT NULL,
 `Nome` varchar(100) NOT NULL,
 `Email` varchar(100) DEFAULT NULL,
 `telefone` varchar(20) DEFAULT NULL,
 PRIMARY KEY (`CPF`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;
CREATE TABLE `ciclomotor` (
 `IDCM` int NOT NULL AUTO_INCREMENT,
 `Nome` varchar(100) NOT NULL,
 `Ano` year DEFAULT NULL,
 `Cor` varchar(30) DEFAULT NULL,
 PRIMARY KEY (`IDCM`)
) ENGINE=InnoDB AUTO_INCREMENT=7 DEFAULT CHARSET=utf8mb3;
CREATE TABLE `locacao` (
 `IDLOC` int NOT NULL AUTO_INCREMENT,
 `Data` date DEFAULT NULL,
 `Local` varchar(150) DEFAULT NULL,
 `Hora` time DEFAULT NULL,
 `PESSOAS_CPF` varchar(11) NOT NULL,
 `CICLOMOTOR_IDCM` int NOT NULL,
 PRIMARY KEY (`IDLOC`),
 KEY `fk_LOCAÇÃO_PESSOAS_idx` (`PESSOAS_CPF`),
 KEY `fk_LOCAÇÃO_CICLOMOTOR1_idx` (`CICLOMOTOR_IDCM`),
 CONSTRAINT `fk_LOCAÇÃO_CICLOMOTOR1` FOREIGN KEY (`CICLOMOTOR_IDCM`) REFERENCES `ciclomotor` (`IDCM`),
 CONSTRAINT `fk_LOCAÇÃO_PESSOAS` FOREIGN KEY (`PESSOAS_CPF`) REFERENCES `pessoas` (`CPF`)
) ENGINE=InnoDB AUTO_INCREMENT=9 DEFAULT CHARSET=utf8mb3;
CREATE TABLE `trajeto` (
 `IDTRAJETO` int NOT NULL AUTO_INCREMENT,
 `Data` date DEFAULT NULL,
 `Hora` time DEFAULT NULL,
 `Local` varchar(150) DEFAULT NULL,
 `CICLOMOTOR_IDCM` int NOT NULL,
 PRIMARY KEY (`IDTRAJETO`),
 KEY `fk_TRAJETO_CICLOMOTOR1_idx` (`CICLOMOTOR_IDCM`),
 CONSTRAINT `fk_TRAJETO_CICLOMOTOR1` FOREIGN KEY (`CICLOMOTOR_IDCM`) REFERENCES `ciclomotor` (`IDCM`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb3;
